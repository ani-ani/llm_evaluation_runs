@cocotb.test(timeout_time=5000, timeout_unit="ms")
async def test_potato_optimizer(dut):
    """Main test function for potato optimizer."""
    
    # Start clock
    cocotb.start_soon(Clock(dut.clk, CLK_PERIOD_NS, units='ns').start())
    
    # Reset
    await reset_dut(dut)
    
    # Test cases: (N, L, a_list, c_list, expected_product_str)
    # Expected products are from the problem statement
    test_cases = [
        (3, 1, [3, 2, 1], [1, 2, 3], "0.556"),
        (3, 2, [2, 2, 2], [3, 3, 3], "2.250"),
    ]
    
    passed = 0
    failed = 0
    
    for i, (N, L, a_list, c_list, expected_str) in enumerate(test_cases):
        cocotb.log.info(f"Test {i+1}: N={N}, L={L}, a={a_list}, c={c_list}")
        
        try:
            # Write N and L
            dut.N.value = N
            dut.L.value = L
            
            # Write arrays using the helper function
            await write_array(dut, 'a', a_list, DATA_WIDTH)
            await write_array(dut, 'c', c_list, COST_WIDTH)
            
            # Start computation
            await start_computation(dut)
            
            # Wait for done
            await wait_for_done(dut)
            
            # Read result
            if not is_value_defined(dut.result.value):
                raise TestFailure(f"Result is undefined (X/Z)")
            
            result_raw = int(dut.result.value)
            
            # Convert from 16.16 fixed-point to float
            result_float = result_raw / (1 << 16)
            
            # Parse expected value
            expected_float = float(expected_str)
            
            # Check if result is close (within reasonable tolerance for fixed-point)
            tolerance = 0.01  # Allow 1% error due to fixed-point precision
            if abs(result_float - expected_float) > tolerance:
                raise TestFailure(f"Product mismatch: expected {expected_float:.3f}, got {result_float:.3f} (raw: {result_raw})")
            
            cocotb.log.info(f"  PASS: product = {result_float:.3f} (expected {expected_float:.3f})")
            passed += 1
            
        except TestFailure as e:
            cocotb.log.error(f"  FAIL: {e}")
            failed += 1
    
    # Summary
    cocotb.log.info(f"{'='*50}")
    cocotb.log.info(f"Results: {passed}/{passed+failed} tests passed")
    
    if failed > 0:
        raise TestFailure(f"{failed} tests failed")