@cocotb.test(timeout_time=5000, timeout_unit="ms")
async def test_example1(dut):
    """Test the first example: N=6, K=2, a=[3,4,5,6,1,2], expected f=[5,6,1,2,3,4]."""
    
    # Start clock
    cocotb.start_soon(Clock(dut.clk, CLK_PERIOD_NS, units='ns').start())
    
    # Reset
    await reset_dut(dut)
    
    # Get array size (should be 6)
    N = len(dut.a)
    if N != 6:
        raise TestFailure(f"DUT has array size {N}, expected 6 for this test")
    
    # Test case data
    K = 2
    a_values = [3, 4, 5, 6, 1, 2]
    expected_f = [5, 6, 1, 2, 3, 4]
    
    # Write inputs
    dut.K.value = K
    await write_array(dut, 'a', a_values, DATA_WIDTH)
    
    # Start computation
    await start_computation(dut)
    
    # Wait for valid
    await wait_for_done(dut)
    
    # Check error flag
    if has_signal(dut, 'error'):
        if int(dut.error.value) == 1:
            raise TestFailure("Error flag asserted, but solution exists")
    
    # Read output f
    f_values = await read_array(dut, 'f', N)
    
    # Verify
    for i in range(N):
        if f_values[i] is None:
            raise TestFailure(f"f[{i}] is undefined")
        if f_values[i] != expected_f[i]:
            raise TestFailure(f"f[{i}] mismatch: expected {expected_f[i]}, got {f_values[i]}")
    
    cocotb.log.info("Test passed: f matches expected output")

