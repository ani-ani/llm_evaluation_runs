                            if (count > 32'd2) begin
                                collinear_sum <= (collinear_sum + (pow2[count] - count - 32'd1)) % MOD;
                            end
                        end
                    end

                    // Final result
                    result <= (total_subsets - collinear_sum) % MOD;
                    next_state <= FINISH;
                end
                FINISH: begin
                    done <= 1'b1;
                    next_state <= IDLE;
                end
                default: next_state <= IDLE;
            endcase
        end
    end

    // Cycle counter for safety
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cycle_count <= 8'd0;
        end else begin
            if (state == COMPUTE) begin
                cycle_count <= cycle_count + 8'd1;
                if (cycle_count >= MAX_CYCLES) begin
                    next_state <= FINISH;
                end
            end else begin
                cycle_count <= 8'd0;
            end
        end
    end

endmodule