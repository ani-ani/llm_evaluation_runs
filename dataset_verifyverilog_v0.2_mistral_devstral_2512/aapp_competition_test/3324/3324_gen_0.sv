            for (int j = 0; j < 10; j++) begin
              matrix[i][j] <= matrix_in[i][j];
            end
          end
          state <= PARSED_DATA_READY;
        end
        PARSED_DATA_READY: begin
          state <= PIVOT_FIND;
        end
        PIVOT_FIND: begin
          // Find pivot
          if (current_col < num_elements) begin
            pivot_row <= current_row;
            while (pivot_row < num_molecules && matrix[pivot_row][current_col] == 0) begin
              pivot_row <= pivot_row + 1;
            end
            if (pivot_row < num_molecules) begin
              state <= PIVOT_NORMALIZE;
            end else begin
              current_col <= current_col + 1;
            end
          end else begin
            state <= BACK_SUBSTITUTE;
          end
        end
        PIVOT_NORMALIZE: begin
          // Normalize pivot row
          temp_pivot <= matrix[pivot_row][current_col];
          for (int j = 0; j < num_elements; j++) begin
            matrix[pivot_row][j] <= matrix[pivot_row][j] / temp_pivot;
          end
          state <= ELIMINATE;
        end
        ELIMINATE: begin
          // Eliminate column
          for (int i = 0; i < num_molecules; i++) begin
            if (i != pivot_row) begin
              temp_elim <= matrix[i][current_col];
              for (int j = 0; j < num_elements; j++) begin
                matrix[i][j] <= matrix[i][j] - temp_elim * matrix[pivot_row][j];
              end
            end
          end
          current_row <= current_row + 1;
          current_col <= current_col + 1;
          state <= PIVOT_FIND;
        end
        BACK_SUBSTITUTE: begin
          // Back substitution
          for (int i = 0; i < num_molecules; i++) begin
            coeffs[i] <= 1;
          end
          state <= NORMALIZE_OUTPUT;
        end
        NORMALIZE_OUTPUT: begin
          // Normalize output
          gcd_val <= 1;
          for (int i = 0; i < num_molecules; i++) begin
            temp_gcd <= gcd(gcd_val, coeffs[i]);
            gcd_val <= temp_gcd;
          end
          for (int i = 0; i < num_molecules; i++) begin
            coefficients[i] <= coeffs[i] / gcd_val;
          end
          valid <= 1;
          state <= DONE;
        end
        DONE: begin
          done <= 1;
        end
      endcase
    end
  end

  // GCD function
  function [15:0] gcd;
    input [15:0] a;
    input [15:0] b;
    reg [15:0] x;
    reg [15:0] y;
    begin
      x = a;
      y = b;
      while (y != 0) begin
        temp_rem = x % y;
        x = y;
        y = temp_rem;
      end
      gcd = x;
    end
  endfunction

