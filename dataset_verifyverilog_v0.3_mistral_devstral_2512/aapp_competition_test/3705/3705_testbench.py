@cocotb.test(timeout_time=5000, timeout_unit='ms')
async def test_module(dut):
    '''Test the phone_numbers combinational module.'''
    
    for i, (n, s, expected) in enumerate(test_cases):
        cocotb.log.info(f'Test {i+1}: n={n}, string={s}, expected={expected}')
        
        # Convert string to list of integers (each digit)
        digits_list = [int(c) for c in s]
        
        # Pack the digits_list into a 400-bit integer (100 digits × 4 bits each)
        packed_digits = 0
        for j, digit in enumerate(digits_list):
            digit_clamped = clamp_to_width(digit, 4)
            packed_digits |= (digit_clamped << (4 * j))
        
        # Assign to DUT
        dut.n.value = n
        dut.digits.value = packed_digits
        
        # Wait for combinational propagation
        await Timer(1, units='ns')
        
        # Read result
        if not is_value_defined(dut.result.value):
            raise TestFailure(f'Test {i+1}: Result is undefined (X/Z)')
        
        result = int(dut.result.value)
        
        if result != expected:
            raise TestFailure(f'Test {i+1}: expected {expected}, got {result}')
        
        cocotb.log.info(f'  PASS: result = {result}')
    
    cocotb.log.info(f'{'='*50}')
    cocotb.log.info(f'All tests passed!')