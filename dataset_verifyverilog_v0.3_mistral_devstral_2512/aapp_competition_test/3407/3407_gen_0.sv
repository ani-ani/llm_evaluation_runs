module tree_embedder (
    input        clk,
    input        rst_n,
    input        start,
    input  [3:0] n,
    input  [2:0] edge_a [6:0],
    input  [2:0] edge_b [6:0],
    input  [6:0] edge_valid,
    output reg [31:0] x [7:0],
    output reg [31:0] y [7:0],
    output reg done
);

    // Fixed-point format: Q16.16 (16 integer bits, 16 fractional bits)
    // Sine/Cosine lookup table: 256 entries for angles 0..2π
    // Values stored as 32-bit Q16.16
    reg [31:0] sin_lut [0:255];
    reg [31:0] cos_lut [0:255];
    initial begin
        // Pre-computed values for sine and cosine (Q16.16)
        // This is a subset; full table would be generated by a script
        sin_lut[0] = 32'h00000000;  // sin(0) = 0
        cos_lut[0] = 32'h00010000;  // cos(0) = 1
        sin_lut[64] = 32'h00010000; // sin(π/2) = 1
        cos_lut[64] = 32'h00000000; // cos(π/2) = 0
        sin_lut[128] = 32'h00000000; // sin(π) = 0
        cos_lut[128] = 32'hFFFF0000; // cos(π) = -1
        sin_lut[192] = 32'hFFFF0000; // sin(3π/2) = -1
        cos_lut[192] = 32'h00000000; // cos(3π/2) = 0
        // Fill others with placeholder (for brevity, in real design would be full)
        for (integer i=1; i<64; i=i+1) begin
            sin_lut[i] = 32'h00000000;
            cos_lut[i] = 32'h00010000;
        end
        for (integer i=65; i<128; i=i+1) begin
            sin_lut[i] = 32'h00000000;
            cos_lut[i] = 32'h00000000;
        end
        for (integer i=129; i<192; i=i+1) begin
            sin_lut[i] = 32'h00000000;
            cos_lut[i] = 32'h00000000;
        end
        for (integer i=193; i<256; i=i+1) begin
            sin_lut[i] = 32'h00000000;
            cos_lut[i] = 32'h00000000;
        end
    end

    // Reciprocals for divisors 1..8 (Q16.16)
    // 1/1 = 1.0, 1/2 = 0.5, 1/3 ≈ 0.33333, etc.
    reg [31:0] reciprocal [0:7];
    initial begin
        reciprocal[0] = 32'h00010000; // 1/1 = 1.0
        reciprocal[1] = 32'h00008000; // 1/2 = 0.5
        reciprocal[2] = 32'h00005555; // 1/3 ≈ 0.33333
        reciprocal[3] = 32'h00004000; // 1/4 = 0.25
        reciprocal[4] = 32'h00003333; // 1/5 ≈ 0.2
        reciprocal[5] = 32'h00002AAA; // 1/6 ≈ 0.16667
        reciprocal[6] = 32'h00002492; // 1/7 ≈ 0.14286
        reciprocal[7] = 32'h00002000; // 1/8 = 0.125
    end

    // State machine
    localparam [2:0] S_IDLE = 3'd0;
    localparam [2:0] S_BUILD_ADJ = 3'd1;
    localparam [2:0] S_SIZE_DFS = 3'd2;
    localparam [2:0] S_COORD_DFS = 3'd3;
    localparam [2:0] S_DONE = 3'd4;
    reg [2:0] state;

    // Adjacency matrix (8x8)
    reg [7:0] adj [7:0];

    // Subtree sizes
    reg [3:0] sub_size [7:0];

    // DFS stack
    reg [2:0] stack_node [7:0];
    reg [2:0] stack_parent [7:0];
    reg [2:0] stack_ptr;
    reg [2:0] stack_child_idx [7:0]; // which child we are processing

    // Current node for coordinate DFS
    reg [2:0] curr_node;
    reg [2:0] curr_parent;
    reg [31:0] curr_x;
    reg [31:0] curr_y;
    reg [31:0] parent_x;
    reg [31:0] parent_y;
    reg [31:0] cum_angle; // Q16.16 turns (0..1)
    reg [3:0] child_idx;  // which child we are placing
    reg [3:0] total_children;
    reg [31:0] angle_center; // Q16.16 turns
    reg [7:0] angle_index; // 0..255
    reg signed [31:0] delta_x, delta_y;

    integer i, j;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state <= S_IDLE;
            done <= 1'b0;
            for (i=0; i<8; i=i+1) begin
                x[i] <= 32'd0;
                y[i] <= 32'd0;
                adj[i] <= 8'd0;
                sub_size[i] <= 4'd0;
            end
            stack_ptr <= 3'd0;
            curr_node <= 3'd0;
            child_idx <= 4'd0;
            total_children <= 4'd0;
        end else begin
            case (state)
                S_IDLE: begin
                    done <= 1'b0;
                    if (start) begin
                        // Reset adjacency matrix
                        for (i=0; i<8; i=i+1) adj[i] <= 8'd0;
                        state <= S_BUILD_ADJ;
                    end
                end

                S_BUILD_ADJ: begin
                    // Build adjacency matrix from edge inputs
                    for (i=0; i<7; i=i+1) begin
                        if (edge_valid[i]) begin
                            // Convert to 0-based indices
                            adj[edge_a[i]-1] <= adj[edge_a[i]-1] | (1 << (edge_b[i]-1));
                            adj[edge_b[i]-1] <= adj[edge_b[i]-1] | (1 << (edge_a[i]-1));
                        end
                    end
                    // Initialize sub_size to 1
                    for (i=0; i<8; i=i+1) sub_size[i] <= 4'd1;
                    stack_ptr <= 3'd0;
                    state <= S_SIZE_DFS;
                end

                S_SIZE_DFS: begin
                    // Compute subtree sizes using iterative DFS
                    if (stack_ptr == 0) begin
                        // Start DFS from node 0 (root)
                        stack_node[0] <= 3'd0;
                        stack_parent[0] <= 3'd8; // 8 means no parent
                        stack_child_idx[0] <= 3'd0;
                        stack_ptr <= 3'd1;
                    end else begin
                        // Pop current node
                        if (stack_child_idx[stack_ptr-1] >= 8) begin
                            // All children processed, back-propagate size
                            stack_ptr <= stack_ptr - 1;
                            if (stack_ptr > 1) begin
                                // Add size to parent
                                sub_size[stack_parent[stack_ptr-1]] <= sub_size[stack_parent[stack_ptr-1]] + sub_size[stack_node[stack_ptr-1]];
                                // Move to next child of parent
                                stack_child_idx[stack_ptr-1] <= stack_child_idx[stack_ptr-1] + 1;
                            end
                        end else begin
                            // Check next child
                            integer child = stack_child_idx[stack_ptr-1];
                            if (adj[stack_node[stack_ptr-1]][child] && child != stack_parent[stack_ptr-1]) begin
                                // Push child
                                stack_node[stack_ptr] <= child;
                                stack_parent[stack_ptr] <= stack_node[stack_ptr-1];
                                stack_child_idx[stack_ptr] <= 3'd0;
                                stack_ptr <= stack_ptr + 1;
                            end else begin
                                // Not a child, try next
                                stack_child_idx[stack_ptr-1] <= stack_child_idx[stack_ptr-1] + 1;
                            end
                        end
                    end
                    // When stack_ptr becomes 0 again, sizes are computed
                    if (stack_ptr == 0 && start) begin
                        state <= S_COORD_DFS;
                        // Reset coordinate DFS state
                        curr_node <= 3'd0;
                        curr_parent <= 3'd8;
                        curr_x <= 32'd0;
                        curr_y <= 32'd0;
                        x[0] <= 32'd0;
                        y[0] <= 32'd0;
                        cum_angle <= 32'd0;
                        child_idx <= 4'd0;
                        total_children <= 4'd0;
                        // Count children of root
                        for (i=0; i<8; i=i+1) begin
                            if (adj[0][i] && i != 8) total_children <= total_children + 1;
                        end
                    end
                end

                S_COORD_DFS: begin
                    // Place children of curr_node
                    if (child_idx < 8) begin
                        // Find next valid child
                        if (adj[curr_node][child_idx] && child_idx != curr_parent) begin
                            // Compute sector size for this child
                            // sector_turns = reciprocal[sub_size[curr_node]-1] * sub_size[child_idx]
                            // We need to multiply two Q16.16 numbers, then take upper bits
                            reg [63:0] temp_prod;
                            temp_prod = {32'h0, reciprocal[sub_size[curr_node]-1]} * {32'h0, sub_size[child_idx]};
                            // temp_prod[47:16] is Q16.16 result
                            reg [31:0] sector_turns = temp_prod[47:16];
                            // Angle center = cum_angle + sector_turns/2
                            reg [31:0] half_sector = sector_turns >> 1;
                            angle_center = cum_angle + half_sector;
                            // Convert angle_center (0..1) to LUT index (0..255)
                            // angle_index = angle_center * 256 >> 16
                            angle_index = (angle_center * 256) >> 16;
                            // Get sine and cosine from LUT
                            reg signed [31:0] sin_val = sin_lut[angle_index];
                            reg signed [31:0] cos_val = cos_lut[angle_index];
                            // Child coordinates = parent + (cos, sin)
                            // parent coordinates are in curr_x, curr_y
                            // We need to sign-extend the 32-bit values to 64 bits for addition
                            reg signed [63:0] new_x = {{32{curr_x[31]}}, curr_x} + {{32{cos_val[31]}}, cos_val};
                            reg signed [63:0] new_y = {{32{curr_y[31]}}, curr_y} + {{32{sin_val[31]}}, sin_val};
                            // Store child coordinates
                            x[child_idx] <= new_x[31:0];
                            y[child_idx] <= new_y[31:0];
                            // Push child onto stack for further processing
                            stack_node[stack_ptr] <= child_idx;
                            stack_parent[stack_ptr] <= curr_node;
                            stack_child_idx[stack_ptr] <= 3'd0;
                            stack_ptr <= stack_ptr + 1;
                            // Update cumulative angle
                            cum_angle <= cum_angle + sector_turns;
                            // Move to next child of current node
                            child_idx <= child_idx + 1;
                        end else begin
                            // Not a child, try next
                            child_idx <= child_idx + 1;
                        end
                    end else begin
                        // All children of curr_node placed, pop stack
                        if (stack_ptr > 0) begin
                            // Move to next node on stack
                            curr_node <= stack_node[stack_ptr-1];
                            curr_parent <= stack_parent[stack_ptr-1];
                            curr_x <= x[stack_node[stack_ptr-1]];
                            curr_y <= y[stack_node[stack_ptr-1]];
                            // Reset child index and cumulative angle for new node
                            child_idx <= 4'd0;
                            cum_angle <= 32'd0;
                            // Count children of new node
                            total_children <= 4'd0;
                            for (i=0; i<8; i=i+1) begin
                                if (adj[curr_node][i] && i != curr_parent) total_children <= total_children + 1;
                            end
                            stack_ptr <= stack_ptr - 1;
                        end else begin
                            // All nodes placed
                            state <= S_DONE;
                            done <= 1'b1;
                        end
                    end
                end

                S_DONE: begin
                    done <= 1'b0;
                    state <= S_IDLE;
                end

                default: state <= S_IDLE;
            endcase
        end
    end
endmodule