@cocotb.test(timeout_time=5000, timeout_unit="ms")
async def test_appleman_toastman(dut):
    """Test the Appleman-Toastman module."""
    
    # Start clock
    cocotb.start_soon(Clock(dut.clk, CLK_PERIOD_NS, units='ns').start())
    
    # Reset
    await reset_dut(dut)
    
    # Define test cases: (len, arr_values, expected_output, description)
    test_cases = [
        (1, [10, 0, 0, 0], 10, "Single element"),
        (2, [1, 2, 0, 0], 6, "Two elements [1,2]"),
        (3, [3, 1, 5, 0], 26, "Example from problem"),
        (4, [5, 2, 6, 10], 85, "Four elements"),
        (4, [10, 10, 10, 10], 120, "All equal"),
    ]
    
    passed = 0
    failed = 0
    
    for i, (len_val, arr_vals, expected, description) in enumerate(test_cases):
        cocotb.log.info(f"Test {i+1}: {description}")
        
        try:
            # Set len
            dut.len.value = len_val
            
            # Set array values individually
            dut.arr_0.value = clamp_to_width(arr_vals[0], DATA_WIDTH)
            dut.arr_1.value = clamp_to_width(arr_vals[1], DATA_WIDTH)
            dut.arr_2.value = clamp_to_width(arr_vals[2], DATA_WIDTH)
            dut.arr_3.value = clamp_to_width(arr_vals[3], DATA_WIDTH)
            
            # Start computation
            await start_computation(dut)
            
            # Wait for done
            await wait_for_done(dut)
            
            # Read result
            if not is_value_defined(dut.result.value):
                raise TestFailure(f"Result is undefined (X/Z)")
            
            result = int(dut.result.value)
            
            if result != expected:
                raise TestFailure(f"Expected {expected}, got {result}")
            
            cocotb.log.info(f"  PASS: result = {result}")
            passed += 1
            
        except TestFailure as e:
            cocotb.log.error(f"  FAIL: {e}")
            failed += 1
        
        # Wait a few cycles before next test
        await Timer(100, units='ns')
        await RisingEdge(dut.clk)
    
    # Summary
    cocotb.log.info(f"{'='*50}")
    cocotb.log.info(f"Results: {passed}/{passed+failed} tests passed")
    
    if failed > 0:
        raise TestFailure(f"{failed} tests failed")