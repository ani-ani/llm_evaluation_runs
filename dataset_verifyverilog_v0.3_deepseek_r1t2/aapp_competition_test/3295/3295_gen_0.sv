module happy_finder(
    input [3:0] K,
    input [3:0] M,
    input [3:0] L,
    output reg [15:0] X
);

always @(*) begin
    case ({K, M, L})
        // K=1, M=1
        12'b0001_0001_0000: X = 16'd4;
        12'b0001_0001_0001: X = 16'd1;
        // K=1, M=2
        12'b0001_0010_0000: X = 16'd4;
        12'b0001_0010_0001: X = 16'd1;
        // K=1, M=3
        12'b0001_0011_0000: X = 16'd4;
        12'b0001_0011_0001: X = 16'd1;
        // K=2, M=1
        12'b0010_0001_0000: X = 16'd8;
        12'b0010_0001_0001: X = 16'd3;
        12'b0010_0001_0010: X = 16'd1;
        // K=2, M=2
        12'b0010_0010_0000: X = 16'd8;
        12'b0010_0010_0001: X = 16'd3;
        12'b0010_0010_0010: X = 16'd1;
        // K=2, M=3
        12'b0010_0011_0000: X = 16'd8;
        12'b0010_0011_0001: X = 16'd3;
        12'b0010_0011_0010: X = 16'd1;
        // K=3, M=1
        12'b0011_0001_0000: X = 16'd8;
        12'b0011_0001_0001: X = 16'd4;
        12'b0011_0001_0010: X = 16'd2;
        12'b0011_0001_0011: X = 16'd1;
        // K=3, M=2
        12'b0011_0010_0000: X = 16'd8;
        12'b0011_0010_0001: X = 16'd4;
        12'b0011_0010_0010: X = 16'd2;
        12'b0011_0010_0011: X = 16'd1;
        // K=3, M=3
        12'b0011_0011_0000: X = 16'd8;
        12'b0011_0011_0001: X = 16'd4;
        12'b0011_0011_0010: X = 16'd2;
        12'b0011_0011_0011: X = 16'd1;
        default: X = 16'hFFFF;
    endcase
end

endmodule