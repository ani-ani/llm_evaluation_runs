import cocotb
from cocotb.triggers import Timer, RisingEdge
from cocotb.clock import Clock

@cocotb.test()
async def test_baron_munchausen(dut):
    # Setup clock
    clock = Clock(dut.clk, 10, units="ns")
    cocotb.start_soon(clock.start())

    # Reset
    dut.rst_n.value = 0
    dut.start.value = 0
    dut.a.value = 0
    await RisingEdge(dut.clk)
    await RisingEdge(dut.clk)
    dut.rst_n.value = 1
    await RisingEdge(dut.clk)

    async def run_test(a_val, expected_n):
        dut._log.info(f"Testing a={a_val}")
        dut.a.value = a_val
        dut.start.value = 1
        await RisingEdge(dut.clk)
        dut.start.value = 0
        
        # Wait for done (with timeout)
        timeout = 60000 # Should be enough for 10000 iterations
        for _ in range(timeout):
            await RisingEdge(dut.clk)
            if dut.done.value == 1:
                break
        else:
            raise TimeoutError("Module did not finish in time")

        result = int(dut.result.value)
        dut._log.info(f"Result: {result}, Expected: {expected_n}")
        assert result == expected_n, f"Mismatch for a={a_val}: got {result}, expected {expected_n}"

